/// Production secrets must be materialized on Linux tmpfs/ramfs, not on the
/// persistent data volume. This does not protect swap or hibernation images.
pub fn require_memory_file(path: &Path) -> Result<(), Error> {
    #[cfg(target_os = "linux")]
    {
        let file = read_private_file(path)?;
        let filesystem = rustix::fs::fstatfs(&file).map_err(|_| Error::Io)?;
        // TMPFS_MAGIC / RAMFS_MAGIC from linux/magic.h.
        let kind = u64::try_from(filesystem.f_type).map_err(|_| Error::Unsupported)?;
        if matches!(kind, 0x0102_1994 | 0x8584_58f6) {
            return Ok(());
        }
        Err(Error::Path)
    }
    #[cfg(not(target_os = "linux"))]
    {
        let _ = path;
        Err(Error::Unsupported)
    }
}

/// Call before reading any server secrets. This does not defend against host root.
pub fn disable_process_dumps() -> Result<(), Error> {
    #[cfg(unix)]
    rustix::process::setrlimit(
        rustix::process::Resource::Core,
        rustix::process::Rlimit {
            current: Some(0),
            maximum: Some(0),
        },
    )
    .map_err(|_| Error::Io)?;
    #[cfg(target_os = "linux")]
    rustix::process::set_dumpable_behavior(rustix::process::DumpableBehavior::NotDumpable)
        .map_err(|_| Error::Io)?;
    Ok(())
}

/// Stable SQLCipher 4 with the September 2026 security fixes. Major-format changes
/// require a reviewed migration instead of silently accepting a new default.
pub fn supported_sqlcipher_version(version: &str) -> bool {
    let Some(version) = version.split_whitespace().next() else {
        return false;
    };
    let mut parts = version.split('.');
    matches!(parts.next(), Some("4"))
        && parts
            .next()
            .and_then(|part| part.parse::<u32>().ok())
            .is_some_and(|minor| minor >= 19)
        && parts
            .next()
            .and_then(|part| part.parse::<u32>().ok())
            .is_some()
        && parts.next().is_none()
}
