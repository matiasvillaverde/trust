//! OS file boundaries and raw SQLCipher keys. No application cryptography lives here.
use std::{
    fmt,
    fs::File,
    io::{Read, Write},
    path::Path,
};
use zeroize::Zeroizing;

#[derive(Debug, thiserror::Error)]
pub enum Error {
    #[error(
        "Cannot access protected storage; check ownership, permissions and mount availability"
    )]
    Io,
    #[error("Protected files must be regular, singly linked, owned by the service or root, and inaccessible to group/other users")]
    PrivateFile,
    #[error("Protected paths cannot contain symlinks or untrusted writable directories")]
    Path,
    #[error("Secret is empty or exceeds its size limit")]
    Size,
    #[error("Database keys must contain exactly 64 hexadecimal characters generated by a cryptographic random source")]
    Key,
    #[error("Protected server storage requires Unix permission checks on this platform")]
    Unsupported,
}

/// A 256-bit SQLCipher raw key. Debug output never includes key material.
pub struct DatabaseKey(Zeroizing<String>);
impl fmt::Debug for DatabaseKey {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str("DatabaseKey([REDACTED])")
    }
}
impl DatabaseKey {
    pub fn load(path: &Path) -> Result<Self, Error> {
        let bytes = read_secret(path, 66)?;
        let text = std::str::from_utf8(&bytes).map_err(|_| Error::Key)?;
        Self::from_hex(text.trim_end_matches(['\r', '\n']))
    }
    pub fn from_hex(text: &str) -> Result<Self, Error> {
        if text.len() != 64 || !text.bytes().all(|byte| byte.is_ascii_hexdigit()) {
            return Err(Error::Key);
        }
        Ok(Self(Zeroizing::new(text.to_ascii_lowercase())))
    }
    pub fn generate() -> Result<Self, Error> {
        use std::fmt::Write as _;
        let mut bytes = Zeroizing::new([0u8; 32]);
        getrandom::fill(bytes.as_mut()).map_err(|_| Error::Io)?;
        let mut encoded = Zeroizing::new(String::with_capacity(64));
        for byte in bytes.iter() {
            write!(encoded, "{byte:02x}").map_err(|_| Error::Io)?;
        }
        Ok(Self(encoded))
    }
    /// Exclusively create a key file; never overwrite an existing recovery key.
    pub fn write_new(&self, path: &Path) -> Result<(), Error> {
        let mut file = private_file(path, true)?;
        file.write_all(self.0.as_bytes()).map_err(|_| Error::Io)?;
        file.sync_all().map_err(|_| Error::Io)
    }
    /// SQLCipher's documented raw-key syntax. Only validated hex is interpolated.
    /// The caller must never log this value or an SQL query containing it.
    pub fn sql_literal(&self) -> Zeroizing<String> {
        Zeroizing::new(format!("\"x'{}'\"", self.0.as_str()))
    }
    /// The same raw-key syntax for a bound SQLCipher ATTACH parameter.
    pub fn sql_parameter(&self) -> Zeroizing<String> {
        Zeroizing::new(format!("x'{}'", self.0.as_str()))
    }
    /// Compare operator-provisioned keys to reject accidental key reuse.
    pub fn same_as(&self, other: &Self) -> bool {
        self.0.as_bytes() == other.0.as_bytes()
    }
}

#[cfg(unix)]
fn trusted_parents(path: &Path) -> Result<(), Error> {
    use std::os::unix::fs::MetadataExt;
    let absolute = if path.is_absolute() {
        path.to_path_buf()
    } else {
        std::env::current_dir().map_err(|_| Error::Path)?.join(path)
    };
    for parent in absolute.ancestors().skip(1) {
        let metadata = std::fs::symlink_metadata(parent).map_err(|_| Error::Path)?;
        let owned = metadata.uid() == 0 || metadata.uid() == rustix::process::geteuid().as_raw();
        // A private child beneath a root-owned sticky /tmp is safe from other users.
        let sticky = metadata.uid() == 0 && metadata.mode() & 0o1000 != 0;
        if !metadata.is_dir() || !owned || (metadata.mode() & 0o022 != 0 && !sticky) {
            return Err(Error::Path);
        }
    }
    Ok(())
}

/// Create a private directory, rejecting an existing public directory rather than
/// silently changing permissions on an operator-owned path.
#[cfg(unix)]
pub fn private_directory(path: &Path) -> Result<(), Error> {
    use std::os::unix::fs::{DirBuilderExt, MetadataExt};
    // Validate existing ancestors before recursively creating missing components.
    let existing = path
        .ancestors()
        .find(|parent| parent.exists())
        .ok_or(Error::Path)?;
    trusted_parents(&existing.join(".trust-path-check"))?;
    std::fs::DirBuilder::new()
        .recursive(true)
        .mode(0o700)
        .create(path)
        .map_err(|_| Error::Io)?;
    trusted_parents(&path.join(".trust-path-check"))?;
    let metadata = std::fs::symlink_metadata(path).map_err(|_| Error::Io)?;
    if !metadata.is_dir()
        || metadata.uid() != rustix::process::geteuid().as_raw()
        || metadata.mode() & 0o077 != 0
    {
        return Err(Error::PrivateFile);
    }
    Ok(())
}

#[cfg(unix)]
fn check_file(file: &File) -> Result<(), Error> {
    use std::os::unix::fs::MetadataExt;
    let metadata = file.metadata().map_err(|_| Error::Io)?;
    if !metadata.is_file()
        || metadata.nlink() != 1
        || metadata.mode() & 0o077 != 0
        || (metadata.uid() != 0 && metadata.uid() != rustix::process::geteuid().as_raw())
    {
        return Err(Error::PrivateFile);
    }
    Ok(())
}

/// Open/create service data without following a symlink or blocking on a FIFO.
#[cfg(unix)]
pub fn private_file(path: &Path, exclusive: bool) -> Result<File, Error> {
    use std::os::unix::fs::OpenOptionsExt;
    let parent = path
        .parent()
        .filter(|p| !p.as_os_str().is_empty())
        .ok_or(Error::Path)?;
    private_directory(parent)?;
    let mut options = std::fs::OpenOptions::new();
    options
        .read(true)
        .write(true)
        .create(true)
        .truncate(false)
        .create_new(exclusive)
        .mode(0o600)
        .custom_flags(
            i32::try_from((rustix::fs::OFlags::NOFOLLOW | rustix::fs::OFlags::NONBLOCK).bits())
                .map_err(|_| Error::Unsupported)?,
        );
    let file = options.open(path).map_err(|_| Error::Io)?;
    check_file(&file)?;
    Ok(file)
}

/// Read a bounded secret from its opened descriptor, checking that descriptor's
/// metadata instead of trusting a separate pathname check.
#[cfg(unix)]
pub fn read_secret(path: &Path, maximum: u64) -> Result<Zeroizing<Vec<u8>>, Error> {
    let file = read_private_file(path)?;
    let mut bytes = Zeroizing::new(Vec::new());
    file.take(maximum.checked_add(1).ok_or(Error::Size)?)
        .read_to_end(&mut bytes)
        .map_err(|_| Error::Io)?;
    if bytes.is_empty() || u64::try_from(bytes.len()).map_err(|_| Error::Size)? > maximum {
        return Err(Error::Size);
    }
    Ok(bytes)
}

#[cfg(unix)]
pub fn read_private_file(path: &Path) -> Result<File, Error> {
    use std::os::unix::fs::OpenOptionsExt;
    trusted_parents(path)?;
    let file = std::fs::OpenOptions::new()
        .read(true)
        .custom_flags(
            i32::try_from((rustix::fs::OFlags::NOFOLLOW | rustix::fs::OFlags::NONBLOCK).bits())
                .map_err(|_| Error::Unsupported)?,
        )
        .open(path)
        .map_err(|_| Error::Io)?;
    check_file(&file)?;
    Ok(file)
}

/// Public configuration/JWKS may be readable, but never writable by other users.
#[cfg(unix)]
pub fn read_public_config(path: &Path, maximum: u64) -> Result<Vec<u8>, Error> {
    use std::os::unix::fs::{MetadataExt, OpenOptionsExt};
    trusted_parents(path)?;
    let file = std::fs::OpenOptions::new()
        .read(true)
        .custom_flags(
            i32::try_from((rustix::fs::OFlags::NOFOLLOW | rustix::fs::OFlags::NONBLOCK).bits())
                .map_err(|_| Error::Unsupported)?,
        )
        .open(path)
        .map_err(|_| Error::Io)?;
    let metadata = file.metadata().map_err(|_| Error::Io)?;
    if !metadata.is_file()
        || metadata.nlink() != 1
        || metadata.mode() & 0o022 != 0
        || (metadata.uid() != 0 && metadata.uid() != rustix::process::geteuid().as_raw())
    {
        return Err(Error::PrivateFile);
    }
    let mut bytes = Vec::new();
    file.take(maximum.checked_add(1).ok_or(Error::Size)?)
        .read_to_end(&mut bytes)
        .map_err(|_| Error::Io)?;
    if bytes.is_empty() || u64::try_from(bytes.len()).map_err(|_| Error::Size)? > maximum {
        return Err(Error::Size);
    }
    Ok(bytes)
}

